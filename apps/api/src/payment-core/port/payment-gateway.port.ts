import type { NextAction } from './next-action.js';
import type { NormalizedOutcome } from './normalized-outcome.js';

/**
 * The provider-neutral contract every Gateway Plugin implements. Owned by
 * Core; plugins depend on it, Core never depends on a plugin.
 *
 * Errors are reported by throwing one of the `GatewayError` subclasses from
 * `gateway-errors.ts`.
 */
export interface PaymentGateway {
  /** Constant identifier, e.g. `vnpay`. Stored on each PaymentTransaction. */
  readonly gatewayId: string;
  readonly capabilities: GatewayCapabilities;
  /**
   * Lower-case names of the callback request headers Core stores in the
   * webhook inbox (what the plugin needs to re-verify and replay a callback).
   * Every other header is dropped. Absent means none are stored.
   */
  readonly callbackHeaders?: readonly string[];
  /**
   * Whether this plugin talks to the provider's test or live environment, for
   * the operator Gateways view. Absent means test.
   */
  readonly mode?: 'test' | 'live';

  initiate(input: InitiateInput): Promise<InitiateResult>;
  query(input: QueryInput): Promise<QueryResult>;
  /**
   * Present only when `capabilities.supportsCancel` is true. Core checks the
   * flag before calling it.
   */
  cancel?(input: CancelInput): Promise<CancelResult>;
  /** Verifies the signature before anything else, then normalises the payload. */
  parseCallback(input: CallbackInput): Promise<CallbackResult>;
}

export interface GatewayCapabilities {
  readonly supportsCancel: boolean;
}

/** Currencies accepted by the port. Phase 1 is VND only. */
export type GatewayCurrency = 'VND';

/** Opaque JSON bag owned by the plugin; Core stores it and passes it back. */
export type ProviderMetadata = Readonly<Record<string, unknown>>;

export interface InitiateInput {
  /** UUID v7 generated by Core. The plugin formats it into the provider's shape. */
  readonly attemptKey: string;
  /** Decimal string in the currency's major unit (VND: whole dong). The plugin scales it. */
  readonly amount: string;
  readonly currency: GatewayCurrency;
  readonly expiresAt: Date;
  readonly returnUrl: string;
  readonly description: string;
}

export interface InitiateResult {
  readonly providerRef?: string;
  readonly nextAction: NextAction;
  readonly providerMetadata: ProviderMetadata;
  /** The provider's original response, stored for audit and never interpreted. */
  readonly rawPayload: unknown;
}

export interface QueryInput {
  readonly attemptKey: string;
  readonly providerMetadata: ProviderMetadata;
}

export interface QueryResult extends NormalizedOutcome {
  readonly providerRef?: string;
  readonly rawPayload: unknown;
}

export type CancelInput = QueryInput;

export interface CancelResult {
  readonly rawPayload: unknown;
}

export type HeaderValues = Readonly<
  Record<string, string | readonly string[] | undefined>
>;

export interface CallbackInput {
  readonly rawBody: Uint8Array;
  readonly headers: HeaderValues;
  readonly query: HeaderValues;
}

/**
 * What `parseCallback` returns for a verified callback: an outcome for Core to
 * apply, or a notice that the callback is irrelevant.
 */
export type CallbackResult = HandledCallback | IgnoredCallback;

export interface HandledCallback extends NormalizedOutcome {
  readonly ignored?: false;
  /** Derived by the plugin from provider data. */
  readonly attemptKey: string;
  readonly providerRef?: string;
  readonly providerEventId?: string;
  /** The success acknowledgement, in the provider's format. */
  readonly ack: CallbackAck;
}

/**
 * A verified callback PayBridge has no use for: an event type the plugin does
 * not handle, or a provider object PayBridge did not create. Core sends `ack`
 * and stores nothing. Unverified callbacks are never ignored: they throw
 * `InvalidCallbackError`.
 */
export interface IgnoredCallback {
  readonly ignored: true;
  /** The success acknowledgement, in the provider's format. */
  readonly ack: CallbackAck;
}

/** An HTTP response the provider expects in reply to a callback. */
export interface CallbackAck {
  readonly httpStatus: number;
  readonly body: unknown;
  readonly headers?: Readonly<Record<string, string>>;
}
